"""AgentProcessBench, τ² subset, rendered into the competition transcript format.

Source: LulaCola/AgentProcessBench on Hugging Face (MIT), file tau2/test.jsonl: 250 trajectories of
airline, retail and telecom (50 tasks, 5 samples each) with a human label on every agent step:
+1 correct, 0 neutral, -1 wrong. Here every labelled agent step becomes one row: the prompt is the
trajectory up to that step, the response is the step. -1 becomes 1, +1 becomes 0, 0 is dropped.

The trajectories are in English and were generated by other agents on an older τ²-bench version, so
the policy and the tool list are the ones the agent saw in the trajectory, not the ones in our data.

    python scripts/build_apb.py
"""

import argparse
import hashlib
import json
from collections import Counter
from pathlib import Path

import pandas as pd

from guardian.env import setup
from guardian.parsing import format_recognised, parse_transcript, unknown_roles, unparsed_markers
from guardian.render import render_system, render_trajectory

ROOT = Path(__file__).resolve().parents[1]
REPO = "LulaCola/AgentProcessBench"
LABELS = {-1: 1, 1: 0}


def tau2_task(row: dict) -> str | None:
    """τ² task id from the ground-truth action ids ("23_0" is action 0 of task 23), if there are any."""
    actions = (row.get("ground_truth") or {}).get("actions") or []
    return actions[0]["action_id"].rsplit("_", 1)[0] if actions and actions[0].get("action_id") else None


def main() -> None:
    setup()
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, default=ROOT / "data/external/apb/tau2/test.jsonl")
    ap.add_argument("--revision", default="cd81f326aece8b0a3f6359e20df370690d3a98bf")
    ap.add_argument("--out", type=Path, default=ROOT / "data/external/apb_tau2.parquet")
    ap.add_argument("--stats", type=Path, default=ROOT / "results/external_data.json")
    args = ap.parse_args()

    raw = args.source.read_bytes()
    trajectories = [json.loads(line) for line in raw.decode("utf-8").splitlines() if line.strip()]
    records, greetings = [], 0
    for t in trajectories:
        domain = t["data_source"].removeprefix("tau2_")
        system = render_system(t["messages"][0]["content"], t["tools"])
        steps = {s.message_index: s for s in render_trajectory(t["messages"], system)}
        labels = {int(k): v for k, v in t["step_labels"].items()}
        first_error = min((k for k, v in labels.items() if v == -1), default=None)
        for index, value in sorted(labels.items()):
            step = steps.get(index)
            if step is None:
                # the only agent message that is not a step is the unnumbered greeting, never a response
                if index != 1 or t["messages"][index].get("tool_calls"):
                    raise ValueError(f"trajectory {t['total_index']}: labelled message {index} was not rendered")
                greetings += 1
                continue
            if value not in LABELS:
                continue
            records.append(
                {
                    "id": f"apb__{domain}__{t['total_index']}::t{step.turn}",
                    "prompt": step.prompt,
                    "response": step.response,
                    "weak_label": LABELS[value],
                    "source": "agentprocessbench",
                    "source_label": value,
                    "domain": domain,
                    "label_quality": "human_step_label",
                    "first_error": index == first_error,
                    "group": f"{domain}:{t['query_index']}",
                    "tau2_task": tau2_task(t),
                    "sample_index": t["sample_index"],
                }
            )

    frame = pd.DataFrame(records)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    frame.to_parquet(args.out, index=False)

    parse_failures = sum(
        not format_recognised(r.prompt)
        or bool(unparsed_markers(r.prompt) or unparsed_markers(r.response))
        or bool(unknown_roles(parse_transcript(r.prompt)))
        for r in frame.itertuples()
    )
    stats = json.loads(args.stats.read_text(encoding="utf-8")) if args.stats.exists() else {}
    stats["agentprocessbench_tau2"] = {
        "source": f"https://huggingface.co/datasets/{REPO}",
        "revision": args.revision,
        "file": "tau2/test.jsonl",
        "file_sha256": hashlib.sha256(raw).hexdigest(),
        "license": "MIT",
        "trajectories": len(trajectories),
        "tasks": len({(t["data_source"], t["query_index"]) for t in trajectories}),
        "labelled_steps": sum(len(t["step_labels"]) for t in trajectories),
        "source_labels": {str(k): v for k, v in sorted(Counter(frame.source_label).items())},
        "neutral_steps_dropped": sum(v == 0 for t in trajectories for v in t["step_labels"].values()),
        "greeting_steps_skipped": greetings,
        "rows": len(frame),
        "positives": int(frame.weak_label.sum()),
        "negatives": int((frame.weak_label == 0).sum()),
        "first_error_rows": int(frame.first_error.sum()),
        "trajectories_with_an_error": int(sum(any(v == -1 for v in t["step_labels"].values()) for t in trajectories)),
        "by_domain": {d: {"rows": len(g), "positives": int(g.weak_label.sum())} for d, g in frame.groupby("domain")},
        "rows_the_parser_does_not_fully_recognise": int(parse_failures),
        "prompt_chars_p50": int(frame.prompt.str.len().median()),
    }
    args.stats.write_text(json.dumps(stats, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(stats["agentprocessbench_tau2"], ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
